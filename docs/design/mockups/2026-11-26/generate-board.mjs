// Generates board-data.js for the 2026-11-26 play-screen mockups.
// Run once: node docs/design/mockups/2026-11-26/generate-board.mjs
import { writeFileSync } from "node:fs";
import { createRun, applyAction } from "../../../../src/game/game-session.js";

const SEED = "PILOT-CHART";
const REGIONS = {
  foundation: ["echo-hush-v1", "Echo Hush"],
  developing: ["windways-v2", "Windways"],
  capable: ["echo-bridges-v1", "Echo Bridges"],
  advanced: ["tide-doors-v1", "Tide Doors"],
  mastery: ["warden-bells-v1", "Warden Bells"]
};
const start = (region) =>
  createRun(SEED, {
    size: 13,
    wardenCount: 3,
    ruleset: { atlasRegionId: region, revision: REGIONS[region][0], label: REGIONS[region][1] }
  });

// Walk a fixed number of Moves along the shortest route to the nearest Echo.
function walk(run, steps) {
  const dirs = { up: [-1, 0], down: [1, 0], left: [0, -1], right: [0, 1] };
  for (let n = 0; n < steps && run.status === "active" && !run.challenge; n += 1) {
    const size = run.config.size;
    const goal = new Set(run.echoes.filter((e) => !e.collected).map((e) => `${e.row},${e.col}`));
    const from = `${run.explorer.row},${run.explorer.col}`;
    const seen = new Map([[from, null]]);
    const queue = [[run.explorer.row, run.explorer.col]];
    let hit = null;
    while (queue.length && !hit) {
      const [r, c] = queue.shift();
      for (const [name, [dr, dc]] of Object.entries(dirs)) {
        const nr = r + dr, nc = c + dc, key = `${nr},${nc}`;
        if (nr < 0 || nc < 0 || nr >= size || nc >= size || run.labyrinth[nr][nc] !== 1 || seen.has(key)) continue;
        seen.set(key, [`${r},${c}`, name]);
        if (goal.has(key)) { hit = key; break; }
        queue.push([nr, nc]);
      }
    }
    if (!hit) break;
    let step = hit, first = null;
    while (seen.get(step)) { first = seen.get(step)[1]; step = seen.get(step)[0]; }
    run = applyAction(run, { type: "move", direction: first });
  }
  return run;
}

const pick = (run) => ({
  seed: run.seed, ruleset: run.ruleset, size: run.config.size, labyrinth: run.labyrinth,
  explorer: run.explorer, echoes: run.echoes, gate: run.gate, wardens: run.wardens,
  windways: run.windways, echoBridges: run.echoBridges, tideDoors: run.tideDoors,
  signalBells: run.signalBells, revealed: [...run.revealed], pulseVisible: [...run.pulseVisible],
  pulses: run.pulses, pulseBudget: run.config.pulses,
  score: run.score, moves: run.moves, status: run.status, event: run.event
});

// Nine Moves, then one Pulse, so the board shows Fog, map memory, and a Pulse.
const main = applyAction(walk(start("mastery"), 9), { type: "pulse" });
const specimens = Object.fromEntries(Object.keys(REGIONS).map((region) => [region, pick(start(region))]));
const body = `// Generated by generate-board.mjs from createRun("${SEED}"). Do not edit.\nwindow.BOARD = ${JSON.stringify({ main: pick(main), specimens })};\n`;
writeFileSync(new URL("./board-data.js", import.meta.url), body);
